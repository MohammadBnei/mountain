// Command defaultrules writes contract/defaultrules.go: kube-prometheus-stack's default alert rules at a chart
// version, each name with the instances it has (a severity and a for:), read from the chart's templates (each
// `- alert: <name>`, its `severity: {{ dig "<name>" "severity" "<default>" ...}}` and its
// `for: {{ dig "<name>" "for" "<default>" ...}}`; a rule with no for: fires on its first evaluation, 0). Run it by hand against a checkout of the chart's tag
// when infra-bootstrap bumps the chart (atlas reports drift until then), and review the diff:
//
//	git clone --depth 1 --branch kube-prometheus-stack-<version> https://github.com/prometheus-community/helm-charts /tmp/kps
//	go run ./contract/gen/defaultrules /tmp/kps <version> > contract/defaultrules.go && gofmt -w contract/defaultrules.go
//
// Every rule group is listed: infra-bootstrap's values enable them all (they override neither defaultRules.rules nor
// the component toggles); a group the values turn off must be removed by hand, and the generator says which groups it
// read.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"time"
)

var (
	alert = regexp.MustCompile(`(?m)^\s*- alert: ([A-Za-z0-9_]+)\s*$`)
	sev   = regexp.MustCompile(`severity: \{\{ dig "([A-Za-z0-9_]+)" "severity" "([a-z]+)"`)
	// anchored: keep_firing_for is not a for
	forRe = regexp.MustCompile(`(?m)^\s*for: \{\{ dig "([A-Za-z0-9_]+)" "for" "([0-9a-z]+)"`)
)

type rule struct {
	sev string
	sec int
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: defaultrules <helm-charts checkout> <chart version>")
		os.Exit(2)
	}
	dir := filepath.Join(os.Args[1], "charts/kube-prometheus-stack/templates/prometheus/rules-1.14")
	files, _ := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if len(files) == 0 {
		fmt.Fprintln(os.Stderr, "no rule templates under", dir)
		os.Exit(1)
	}
	rules := map[string][]rule{}
	var groups []string
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			panic(err)
		}
		t := string(b)
		locs := alert.FindAllStringSubmatchIndex(t, -1)
		if len(locs) > 0 {
			groups = append(groups, strings.TrimSuffix(filepath.Base(f), ".yaml"))
		}
		for i, l := range locs {
			name, end := t[l[2]:l[3]], len(t)
			if i+1 < len(locs) {
				end = locs[i+1][0]
			}
			s := sev.FindStringSubmatch(t[l[1]:end])
			if s == nil || s[1] != name {
				fmt.Fprintf(os.Stderr, "%s: %s has no severity of its own\n", filepath.Base(f), name)
				os.Exit(1)
			}
			r := rule{sev: s[2]}
			if m := forRe.FindStringSubmatch(t[l[1]:end]); m != nil {
				if m[1] != name {
					fmt.Fprintf(os.Stderr, "%s: %s's for: names %s\n", filepath.Base(f), name, m[1])
					os.Exit(1)
				}
				d, err := time.ParseDuration(m[2])
				if err != nil {
					fmt.Fprintf(os.Stderr, "%s: %s: for %q: %v\n", filepath.Base(f), name, m[2], err)
					os.Exit(1)
				}
				r.sec = int(d / time.Second)
			}
			if !slices.Contains(rules[name], r) {
				rules[name] = append(rules[name], r)
			}
		}
	}
	names := make([]string, 0, len(rules))
	for n := range rules {
		names = append(names, n)
		slices.SortFunc(rules[n], func(a, b rule) int {
			if c := strings.Compare(a.sev, b.sev); c != 0 {
				return c
			}
			return a.sec - b.sec
		})
	}
	slices.Sort(names)
	fmt.Printf("// Code generated by contract/gen/defaultrules from kube-prometheus-stack %s; DO NOT EDIT.\n\npackage contract\n\n", os.Args[2])
	fmt.Printf("// DefaultRulesChart is the kube-prometheus-stack version DefaultRules was read from. atlas reports drift when\n// infra-bootstrap pins another: regenerate (contract/gen/defaultrules).\nconst DefaultRulesChart = %q\n\n", os.Args[2])
	fmt.Printf("// DefaultRules is the chart's default alert rules (groups: %s), name -> its instances (a severity and a for:).\n", strings.Join(groups, ", "))
	fmt.Println("var DefaultRules = map[string][]Rule{")
	for _, n := range names {
		fmt.Printf("\t%q: {%s},\n", n, quoted(rules[n]))
	}
	fmt.Println("}")
}

func quoted(rs []rule) string {
	q := make([]string, len(rs))
	for i, r := range rs {
		q[i] = fmt.Sprintf("{%q, %d}", r.sev, r.sec)
	}
	return strings.Join(q, ", ")
}
